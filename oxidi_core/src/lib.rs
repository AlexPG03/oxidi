//! Oxidi — Zero-cost dependency injection container for Rust.
//!
//! This crate provides the runtime traits and types used by the `oxidi_macros`
//! proc-macro to generate type-safe dependency injection code.
//!
//! # Quick Start
//!
//! ```rust,ignore
//! use oxidi::module;
//! use oxidi::get;
//!
//! // 1. Define the module at the top level (outside any function)
//! module! {
//!     single {
//!         Database::new("postgres://localhost")
//!     }
//!
//!     single {
//!         let db: Database = get();
//!         UserRepository::new(db)
//!     }
//!
//!     factory {
//!         let repo: UserRepository = get();
//!         RequestHandler::new(repo)
//!     }
//! }
//!
//! fn main() {
//!     // 2. Initialize the container
//!     __oxidi_init__();
//!
//!     // 3. Access services from anywhere
//!     let db: Database = get();
//!     let handler = get::<RequestHandler>();
//! }
//! ```
//!
//! # Important
//!
//! - Call `__oxidi_init__()` **before** any `get()` call, otherwise the program will panic.
//! - The `module!()` macro must be placed at the module level (outside any function).
//! - Services must implement `Clone` to be shared between consumers.
//! - For thread-safe sharing without cloning, wrap services in `Arc<T>`.

use std::any::TypeId;
use std::cell::RefCell;
use std::collections::HashMap;
use std::future::Future;
use std::sync::OnceLock;

use task_local::task_local;

pub use oxidi_macros;

#[cfg(feature = "test-support")]
pub mod test_support;

/// Marker trait for modules generated by `module!()`.
///
/// A type that implements this trait represents a DI module that can be
/// initialized with `oxidi::init()`.
#[allow(dead_code)]
pub trait OxidiModule {
    /// The container type generated by the module.
    type Container;
    
    /// Build the container instance.
    fn build() -> Self::Container;
}

/// Convention trait for module extensions (e.g., viewModel, navigation).
///
/// External crates can implement this trait to add new service types
/// that integrate with the oxidi container system.
#[allow(dead_code)]
pub trait OxidiModulePlugin {
    /// The name of the plugin, used in the DSL (e.g., "viewModel").
    const NAME: &'static str;
}

/// Wrapper for factory functions that create new instances on demand.
///
/// Used internally by the generated container code to store factory closures.
#[allow(dead_code)]
pub struct Factory<T, F: Fn() -> T> {
    creator: F,
    _phantom: std::marker::PhantomData<T>,
}

impl<T, F: Fn() -> T> Factory<T, F> {
    /// Create a new factory with the given closure.
    #[allow(dead_code)]
    pub fn new(creator: F) -> Self {
        Self {
            creator,
            _phantom: std::marker::PhantomData,
        }
    }
    
    /// Create a new instance by calling the factory closure.
    pub fn create(&self) -> T {
        (self.creator)()
    }
}

// Re-export the module macro for convenience
pub use oxidi_macros::module;

/// Global container storage using `OnceLock` for explicit initialization.
///
/// The container is stored here after `__oxidi_init__()` is called.
/// All `get()` calls access this global container.
static GLOBAL_CONTAINER: OnceLock<Box<dyn std::any::Any + Send + Sync>> = OnceLock::new();

/// A scope caches scoped service instances created during its lifetime.
///
/// Each scope holds a `HashMap` keyed by `TypeId` that stores one instance
/// per scoped service type. When a scope is dropped, all cached instances
/// are dropped with it.
///
/// `Clone` is required for the `task_local!` approach: when entering a nested
/// scope, we clone the current stack so the inner scope has its own copy.
pub struct Scope {
    cache: HashMap<TypeId, Box<dyn std::any::Any + Send>>,
}

impl Clone for Scope {
    fn clone(&self) -> Self {
        // Clone the cache by cloning each boxed value.
        // Since we store `dyn Any + Send`, we can't clone the values themselves,
        // so we create a new empty cache. Nested scopes start fresh.
        Self {
            cache: HashMap::new(),
        }
    }
}

impl Scope {
    fn new() -> Self {
        Self {
            cache: HashMap::new(),
        }
    }
}

// Task-local stack of active scopes.
// Uses the `task-local` crate which works across `.await` points and is
// compatible with any async runtime (Tokio, async-std, smol, etc.).
// Stored as `RefCell<Option<Vec<Scope>>>` to allow interior mutability
// for caching scoped instances.
task_local! {
    static SCOPE_STACK: RefCell<Option<Vec<Scope>>>;
}

/// Check if a scoped instance of type `T` exists in the current scope.
///
/// Used internally by generated `OxidiResolve` implementations for scoped services.
/// Returns `Some(T)` if the type was already created in the current scope,
/// or `None` if it needs to be created.
pub fn __check_scope_cache<T>() -> Option<T>
where
    T: Clone + 'static,
{
    SCOPE_STACK.try_with(|stack| {
        let stack = stack.borrow();
        match stack.as_ref() {
            Some(scopes) => {
                if let Some(scope) = scopes.last() {
                    let type_id = TypeId::of::<T>();
                    if let Some(cached) = scope.cache.get(&type_id) {
                        return Some(cached.downcast_ref::<T>().unwrap().clone());
                    }
                }
                None
            }
            None => None,
        }
    }).ok().flatten()
}

/// Cache a value in the current scope so subsequent lookups return the same instance.
///
/// Used internally by generated `OxidiResolve` implementations for scoped services.
pub fn __cache_in_scope<T>(val: T)
where
    T: Send + 'static,
{
    SCOPE_STACK.try_with(|stack| {
        let mut stack = stack.borrow_mut();
        if let Some(scopes) = stack.as_mut() {
            if let Some(scope) = scopes.last_mut() {
                let type_id = TypeId::of::<T>();
                scope.cache.insert(type_id, Box::new(val));
            }
        }
    }).ok();
}

/// Enter a new scope and run the closure.
///
/// Inside the closure, `get()` automatically checks the scope first for scoped
/// services, then falls back to global singletons and factories. When the
/// closure returns, the scope (and all scoped instances) are dropped.
///
/// This function works correctly in both sync and async contexts. For async
/// code with `.await` points, prefer `async_scope()` for better performance.
///
/// # Example
///
/// ```rust,ignore
/// use oxidi_core::{module, get, scope};
///
/// module! {
///     single { Database::new("postgres://localhost") }
///
///     scoped {
///         let db: Database = get();
///         Transaction::new(db)
///     }
/// }
///
/// fn main() {
///     __oxidi_init__();
///
///     // Each call to `scope` creates a fresh Transaction
///     scope(|| {
///         let tx: Transaction = get(); // new instance, cached in this scope
///         // ... use tx ...
///     }); // tx is dropped here
///
///     scope(|| {
///         let tx: Transaction = get(); // another new instance
///         // ... use tx ...
///     });
///
///     // Outside a scope, scoped services are not available
///     let db: Database = get(); // global singleton still works
/// }
/// ```
///
/// # Nested Scopes
///
/// Scopes can be nested. An inner scope shadows an outer scope:
///
/// ```rust,ignore
/// scope(|| {
///     let tx1: Transaction = get();
///     scope(|| {
///         let tx2: Transaction = get(); // new instance in inner scope
///         assert!(tx1 != tx2);
///     });
///     let tx3: Transaction = get(); // same as tx1 (outer scope)
///     assert!(tx1 == tx3);
/// }
/// ```
pub fn scope<T>(f: impl FnOnce() -> T) -> T {
    let current = SCOPE_STACK.try_with(|v| v.borrow().clone()).ok().flatten().unwrap_or_default();
    let new_stack = {
        let mut stack = current;
        stack.push(Scope::new());
        stack
    };
    SCOPE_STACK.sync_scope(RefCell::new(Some(new_stack)), f)
}

/// Enter a new scope and run a future.
///
/// Like `scope()`, but designed for async code. The future can contain `.await`
/// points and the scope will be preserved across task migrations between threads.
/// This works with any async runtime (Tokio, async-std, smol, etc.).
///
/// # Example
///
/// ```rust,ignore
/// use oxidi_core::{module, get, async_scope};
///
/// module! {
///     single { Database::new("postgres://localhost") }
///
///     scoped {
///         let db: Database = get();
///         Transaction::new(db)
///     }
/// }
///
/// #[tokio::main]
/// async fn main() {
///     __oxidi_init__();
///
///     async_scope(async {
///         let tx: Transaction = get();
///         tokio::time::sleep(std::time::Duration::from_millis(100)).await;
///         // tx is still available after .await
///         let tx2: Transaction = get();
///         assert_eq!(tx.id(), tx2.id());
///     }).await;
/// }
/// ```
pub async fn async_scope<F, T>(future: F) -> T
where
    F: Future<Output = T>,
{
    let current = SCOPE_STACK.try_with(|v| v.borrow().clone()).ok().flatten().unwrap_or_default();
    let new_stack = {
        let mut stack = current;
        stack.push(Scope::new());
        stack
    };
    SCOPE_STACK.scope(RefCell::new(Some(new_stack)), future).await
}

/// Internal function called by the generated `__oxidi_init__()` to store the container.
/// Do not call this directly — use the `__oxidi_init__()` function generated by `module!()` instead.
pub fn __private_init<C: 'static + Send + Sync>(container: C) {
    GLOBAL_CONTAINER
        .set(Box::new(container))
        .expect("Oxidi container already initialized. Call `__oxidi_init__()` only once.");
}

/// Get a service from the global DI container.
///
/// This function accesses the global container and returns a service of type `T`.
/// When used with assignment (`let db: Database = get()`), the type is inferred
/// automatically.
///
/// # Type Inference
///
/// ```rust,ignore
/// let db: Database = get(); // T inferred from `db`
/// let handler = get::<RequestHandler>(); // Explicit type
/// ```
///
/// # Panics
///
/// Panics if `__oxidi_init__()` has not been called yet. Make sure to initialize
/// the container before any `get()` calls.
///
/// # Requirements
///
/// - The service type `T` must implement `Clone`.
/// - The container must have been initialized with `__oxidi_init__()`.
pub fn get<T>() -> T
where
    T: Clone + OxidiResolve,
{
    let container = GLOBAL_CONTAINER.get().expect(
        "Oxidi container not initialized. Call `__oxidi_init__()` before using `get()`."
    );
    
    // The macro generates a resolve function for each type
    // This is called via the OxidiResolve trait
    <T as OxidiResolve>::resolve(container)
}

/// Try to get a service from the global DI container without panicking.
///
/// This is a non-panicking variant of `get()` that returns `Err` if the
/// container has not been initialized yet. Useful for framework integrations
/// (e.g., Axum extractors) where a panic should be avoided and an HTTP
/// rejection returned instead.
///
/// # Example
///
/// ```rust,ignore
/// match try_get::<Database>() {
///     Ok(db) => { /* use db */ }
///     Err(e) => { /* handle error, e.g., return HTTP 500 */ }
/// }
/// ```
///
/// # Requirements
///
/// - The service type `T` must implement `Clone`.
/// - The container must have been initialized with `__oxidi_init__()`.
pub fn try_get<T>() -> Result<T, &'static str>
where
    T: Clone + OxidiResolve,
{
    match GLOBAL_CONTAINER.get() {
        Some(container) => Ok(<T as OxidiResolve>::resolve(container)),
        None => Err("Oxidi container not initialized. Call `__oxidi_init__()` before using `try_get()`."),
    }
}

/// Trait implemented for each service type by the `module!()` macro.
///
/// The macro generates an implementation of this trait for each service
/// registered in the module. The `resolve` method downcasts the global
/// container and extracts the service.
pub trait OxidiResolve: Clone {
    /// Resolve this service from the global container.
    fn resolve(container: &Box<dyn std::any::Any + Send + Sync>) -> Self;
}
