//! Oxidi — Zero-cost dependency injection container for Rust.
//!
//! This crate provides the runtime traits and types used by the `oxidi_macros`
//! proc-macro to generate type-safe dependency injection code.
//!
//! # Quick Start
//!
//! ```rust,ignore
//! use oxidi::module;
//! use oxidi::get;
//!
//! fn main() {
//!     // Initialize the global container
//!     oxidi::init(module! {
//!         single {
//!             Database::new("postgres://localhost")
//!         }
//!
//!         single {
//!             let db: Database = get();
//!             UserRepository::new(db)
//!         }
//!
//!         factory {
//!             let repo: UserRepository = get();
//!             RequestHandler::new(repo)
//!         }
//!     });
//!
//!     // Access services from anywhere
//!     let db: Database = get();
//!     let handler = get::<RequestHandler>();
//! }
//! ```
//!
//! # Important
//!
//! - Call `oxidi::init()` **before** any `get()` call, otherwise the program will panic.
//! - Services must implement `Clone` to be shared between consumers.
//! - For thread-safe sharing without cloning, wrap services in `Arc<T>`.

use std::sync::OnceLock;

/// Marker trait for modules generated by `module!()`.
///
/// A type that implements this trait represents a DI module that can be
/// initialized with `oxidi::init()`.
pub trait OxidiModule {
    /// The container type generated by the module.
    type Container;
    
    /// Build the container instance.
    fn build() -> Self::Container;
}

/// Convention trait for module extensions (e.g., viewModel, navigation).
///
/// External crates can implement this trait to add new service types
/// that integrate with the oxidi container system.
pub trait OxidiModulePlugin {
    /// The name of the plugin, used in the DSL (e.g., "viewModel").
    const NAME: &'static str;
}

/// Wrapper for factory functions that create new instances on demand.
///
/// Used internally by the generated container code to store factory closures.
pub struct Factory<T, F: Fn() -> T> {
    creator: F,
    _phantom: std::marker::PhantomData<T>,
}

impl<T, F: Fn() -> T> Factory<T, F> {
    /// Create a new factory with the given closure.
    pub fn new(creator: F) -> Self {
        Self {
            creator,
            _phantom: std::marker::PhantomData,
        }
    }
    
    /// Create a new instance by calling the factory closure.
    pub fn create(&self) -> T {
        (self.creator)()
    }
}

// Re-export the module macro for convenience
pub use oxidi_macros::module;

/// Global container storage using `OnceLock` for explicit initialization.
///
/// The container is stored here after `oxidi::init()` is called.
/// All `get()` calls access this global container.
static GLOBAL_CONTAINER: OnceLock<Box<dyn std::any::Any + Send + Sync>> = OnceLock::new();

/// Initialize the global DI container.
///
/// This function must be called **once** at the start of your application,
/// typically in `main()`. It stores the container generated by `module!()`
/// in a global `OnceLock`.
///
/// # Panics
///
/// Panics if called more than once. The container can only be initialized once.
///
/// # Example
///
/// ```rust,ignore
/// fn main() {
///     oxidi::init(module! {
///         single { Database::new("postgres://localhost") }
///         single { UserRepository::new(get::<Database>()) }
///     });
///     
///     // Now services are accessible from anywhere
///     let db: Database = get();
/// }
/// ```
pub fn init<C: 'static + Send + Sync>(container: C) {
    GLOBAL_CONTAINER
        .set(Box::new(container))
        .expect("Oxidi container already initialized. Call `oxidi::init()` only once.");
}

/// Get a service from the global DI container.
///
/// This function accesses the global container and returns a service of type `T`.
/// When used with assignment (`let db: Database = get()`), the type is inferred
/// automatically.
///
/// # Type Inference
///
/// ```rust,ignore
/// let db: Database = get(); // T inferred from `db`
/// let handler = get::<RequestHandler>(); // Explicit type
/// ```
///
/// # Panics
///
/// Panics if `oxidi::init()` has not been called yet. Make sure to initialize
/// the container before any `get()` calls.
///
/// # Requirements
///
/// - The service type `T` must implement `Clone`.
/// - The container must have been initialized with `oxidi::init()`.
pub fn get<T>() -> T
where
    T: Clone + OxidiResolve,
{
    let container = GLOBAL_CONTAINER.get().expect(
        "Oxidi container not initialized. Call `oxidi::init()` before using `get()`."
    );
    
    // The macro generates a resolve function for each type
    // This is called via the OxidiResolve trait
    <T as OxidiResolve>::resolve(container)
}

/// Trait implemented for each service type by the `module!()` macro.
///
/// The macro generates an implementation of this trait for each service
/// registered in the module. The `resolve` method downcasts the global
/// container and extracts the service.
pub trait OxidiResolve: Clone {
    /// Resolve this service from the global container.
    fn resolve(container: &Box<dyn std::any::Any + Send + Sync>) -> Self;
}
