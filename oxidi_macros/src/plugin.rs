/// Convention trait for module extensions (e.g., viewModel, navigation)
///
/// This trait allows external crates to define new service types that integrate
/// with the oxidi container system. Implement this trait to add custom module
/// blocks to the `module!()` DSL.
///
/// # Example
///
/// ```rust,ignore
/// // In oxidi_viewmodel crate:
/// use oxidi_macros::OxidiModulePlugin;
///
/// pub struct ViewModelPlugin;
///
/// impl OxidiModulePlugin for ViewModelPlugin {
///     const NAME: &'static str = "viewModel";
///     
///     fn generate_code(&self) -> proc_macro2::TokenStream {
///         // Generate viewModel-specific code
///         quote! { /* ... */ }
///     }
/// }
/// ```
#[allow(dead_code)]
pub trait OxidiModulePlugin {
    /// The name of the plugin, used in the DSL (e.g., "viewModel")
    const NAME: &'static str;
    
    /// Generate the code for this plugin
    /// This is called by the `module!()` macro when it encounters the plugin's keyword
    fn generate_code(&self) -> proc_macro2::TokenStream;
}

/// Marker trait for modules generated by `module!()`
#[allow(dead_code)]
pub trait OxidiModule {
    /// The container type generated by the module
    type Container;
    
    /// Build the container
    fn build() -> Self::Container;
}
